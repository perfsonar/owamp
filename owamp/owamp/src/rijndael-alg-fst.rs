/// Expand the cipher key into the encryption key schedule.
///
/// Returns the number of rounds for the given key size (`10`/`12`/`14`),
/// or `0` if `key_bits` is not 128/192/256.
///
/// `rk` must hold at least `4 * (Nr + 1)` words (`MAXRK` is always enough).
/// `cipher_key` must be `key_bits/8` bytes.
pub fn rijndael_key_setup_enc(rk: &mut [u32], cipher_key: &[u8], key_bits: i32) -> i32 {
    debug_assert!(rk.len() >= MAXRK);
    let need = (key_bits as usize) / 8;
    if !(key_bits == 128 || key_bits == 192 || key_bits == 256) || cipher_key.len() < need {
        return 0;
    }

    let mut i = 0usize;
    let mut temp: u32;

    rk[0] = get_u32(&cipher_key[0..4]);
    rk[1] = get_u32(&cipher_key[4..8]);
    rk[2] = get_u32(&cipher_key[8..12]);
    rk[3] = get_u32(&cipher_key[12..16]);

    if key_bits == 128 {
        let mut off = 0usize;
        loop {
            temp = rk[off + 3];
            rk[off + 4] = rk[off]
                ^ (Te4[((temp >> 16) & 0xff) as usize] & 0xff00_0000)
                ^ (Te4[((temp >> 8) & 0xff) as usize] & 0x00ff_0000)
                ^ (Te4[(temp & 0xff) as usize] & 0x0000_ff00)
                ^ (Te4[(temp >> 24) as usize] & 0x0000_00ff)
                ^ RCON[i];
            rk[off + 5] = rk[off + 1] ^ rk[off + 4];
            rk[off + 6] = rk[off + 2] ^ rk[off + 5];
            rk[off + 7] = rk[off + 3] ^ rk[off + 6];
            i += 1;
            if i == 10 {
                return 10;
            }
            off += 4;
        }
    }

    rk[4] = get_u32(&cipher_key[16..20]);
    rk[5] = get_u32(&cipher_key[20..24]);
    if key_bits == 192 {
        let mut off = 0usize;
        loop {
            temp = rk[off + 5];
            rk[off + 6] = rk[off]
                ^ (Te4[((temp >> 16) & 0xff) as usize] & 0xff00_0000)
                ^ (Te4[((temp >> 8) & 0xff) as usize] & 0x00ff_0000)
                ^ (Te4[(temp & 0xff) as usize] & 0x0000_ff00)
                ^ (Te4[(temp >> 24) as usize] & 0x0000_00ff)
                ^ RCON[i];
            rk[off + 7] = rk[off + 1] ^ rk[off + 6];
            rk[off + 8] = rk[off + 2] ^ rk[off + 7];
            rk[off + 9] = rk[off + 3] ^ rk[off + 8];
            i += 1;
            if i == 8 {
                return 12;
            }
            rk[off + 10] = rk[off + 4] ^ rk[off + 9];
            rk[off + 11] = rk[off + 5] ^ rk[off + 10];
            off += 6;
        }
    }

    rk[6] = get_u32(&cipher_key[24..28]);
    rk[7] = get_u32(&cipher_key[28..32]);
    if key_bits == 256 {
        let mut off = 0usize;
        loop {
            temp = rk[off + 7];
            rk[off + 8] = rk[off]
                ^ (Te4[((temp >> 16) & 0xff) as usize] & 0xff00_0000)
                ^ (Te4[((temp >> 8) & 0xff) as usize] & 0x00ff_0000)
                ^ (Te4[(temp & 0xff) as usize] & 0x0000_ff00)
                ^ (Te4[(temp >> 24) as usize] & 0x0000_00ff)
                ^ RCON[i];
            rk[off + 9] = rk[off + 1] ^ rk[off + 8];
            rk[off + 10] = rk[off + 2] ^ rk[off + 9];
            rk[off + 11] = rk[off + 3] ^ rk[off + 10];
            i += 1;
            if i == 7 {
                return 14;
            }
            temp = rk[off + 11];
            rk[off + 12] = rk[off + 4]
                ^ (Te4[(temp >> 24) as usize] & 0xff00_0000)
                ^ (Te4[((temp >> 16) & 0xff) as usize] & 0x00ff_0000)
                ^ (Te4[((temp >> 8) & 0xff) as usize] & 0x0000_ff00)
                ^ (Te4[(temp & 0xff) as usize] & 0x0000_00ff);
            rk[off + 13] = rk[off + 5] ^ rk[off + 12];
            rk[off + 14] = rk[off + 6] ^ rk[off + 13];
            rk[off + 15] = rk[off + 7] ^ rk[off + 14];
            off += 8;
        }
    }
    0
}

/// Expand the cipher key into the decryption key schedule.
///
/// Returns the number of rounds, or `0` for invalid `key_bits`.
pub fn rijndael_key_setup_dec(rk: &mut [u32], cipher_key: &[u8], key_bits: i32) -> i32 {
    let nr = rijndael_key_setup_enc(rk, cipher_key, key_bits);
    if nr == 0 {
        return 0;
    }
    // Invert the order of the round keys.
    let mut i = 0usize;
    let mut j = 4 * nr as usize;
    while i < j {
        for k in 0..4 {
            rk.swap(i + k, j + k);
        }
        i += 4;
        j -= 4;
    }
    // Inverse MixColumn on all round keys but first and last.
    for r in 1..nr as usize {
        let off = r * 4;
        for k in 0..4 {
            let t = rk[off + k];
            rk[off + k] = Td0[(Te4[(t >> 24) as usize] & 0xff) as usize]
                ^ Td1[(Te4[((t >> 16) & 0xff) as usize] & 0xff) as usize]
                ^ Td2[(Te4[((t >> 8) & 0xff) as usize] & 0xff) as usize]
                ^ Td3[(Te4[(t & 0xff) as usize] & 0xff) as usize];
        }
    }
    nr
}

/// Encrypt one 16-byte block. `rk` must be an encryption schedule from
/// [`rijndael_key_setup_enc`]; `nr` is that function's return value.
pub fn rijndael_encrypt(rk: &[u32], nr: i32, pt: &[u8; 16], ct: &mut [u8; 16]) {
    let mut s0 = get_u32(&pt[0..4]) ^ rk[0];
    let mut s1 = get_u32(&pt[4..8]) ^ rk[1];
    let mut s2 = get_u32(&pt[8..12]) ^ rk[2];
    let mut s3 = get_u32(&pt[12..16]) ^ rk[3];

    let mut r = nr >> 1;
    let mut rk_off = 0usize;
    let (mut t0, mut t1, mut t2, mut t3);
    loop {
        t0 = Te0[(s0 >> 24) as usize]
            ^ Te1[((s1 >> 16) & 0xff) as usize]
            ^ Te2[((s2 >> 8) & 0xff) as usize]
            ^ Te3[(s3 & 0xff) as usize]
            ^ rk[rk_off + 4];
        t1 = Te0[(s1 >> 24) as usize]
            ^ Te1[((s2 >> 16) & 0xff) as usize]
            ^ Te2[((s3 >> 8) & 0xff) as usize]
            ^ Te3[(s0 & 0xff) as usize]
            ^ rk[rk_off + 5];
        t2 = Te0[(s2 >> 24) as usize]
            ^ Te1[((s3 >> 16) & 0xff) as usize]
            ^ Te2[((s0 >> 8) & 0xff) as usize]
            ^ Te3[(s1 & 0xff) as usize]
            ^ rk[rk_off + 6];
        t3 = Te0[(s3 >> 24) as usize]
            ^ Te1[((s0 >> 16) & 0xff) as usize]
            ^ Te2[((s1 >> 8) & 0xff) as usize]
            ^ Te3[(s2 & 0xff) as usize]
            ^ rk[rk_off + 7];

        rk_off += 8;
        r -= 1;
        if r == 0 {
            break;
        }

        s0 = Te0[(t0 >> 24) as usize]
            ^ Te1[((t1 >> 16) & 0xff) as usize]
            ^ Te2[((t2 >> 8) & 0xff) as usize]
            ^ Te3[(t3 & 0xff) as usize]
            ^ rk[rk_off];
        s1 = Te0[(t1 >> 24) as usize]
            ^ Te1[((t2 >> 16) & 0xff) as usize]
            ^ Te2[((t3 >> 8) & 0xff) as usize]
            ^ Te3[(t0 & 0xff) as usize]
            ^ rk[rk_off + 1];
        s2 = Te0[(t2 >> 24) as usize]
            ^ Te1[((t3 >> 16) & 0xff) as usize]
            ^ Te2[((t0 >> 8) & 0xff) as usize]
            ^ Te3[(t1 & 0xff) as usize]
            ^ rk[rk_off + 2];
        s3 = Te0[(t3 >> 24) as usize]
            ^ Te1[((t0 >> 16) & 0xff) as usize]
            ^ Te2[((t1 >> 8) & 0xff) as usize]
            ^ Te3[(t2 & 0xff) as usize]
            ^ rk[rk_off + 3];
    }

    // Last round (no MixColumns) — rk_off already advanced by 8 past the
    // penultimate pair, matching C `rk += 8` then using rk[0..3] for final.
    s0 = (Te4[(t0 >> 24) as usize] & 0xff00_0000)
        ^ (Te4[((t1 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Te4[((t2 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Te4[(t3 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off];
    put_u32(&mut ct[0..4], s0);
    s1 = (Te4[(t1 >> 24) as usize] & 0xff00_0000)
        ^ (Te4[((t2 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Te4[((t3 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Te4[(t0 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 1];
    put_u32(&mut ct[4..8], s1);
    s2 = (Te4[(t2 >> 24) as usize] & 0xff00_0000)
        ^ (Te4[((t3 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Te4[((t0 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Te4[(t1 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 2];
    put_u32(&mut ct[8..12], s2);
    s3 = (Te4[(t3 >> 24) as usize] & 0xff00_0000)
        ^ (Te4[((t0 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Te4[((t1 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Te4[(t2 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 3];
    put_u32(&mut ct[12..16], s3);
}

/// Decrypt one 16-byte block. `rk` must be a decryption schedule from
/// [`rijndael_key_setup_dec`]; `nr` is that function's return value.
pub fn rijndael_decrypt(rk: &[u32], nr: i32, ct: &[u8; 16], pt: &mut [u8; 16]) {
    let mut s0 = get_u32(&ct[0..4]) ^ rk[0];
    let mut s1 = get_u32(&ct[4..8]) ^ rk[1];
    let mut s2 = get_u32(&ct[8..12]) ^ rk[2];
    let mut s3 = get_u32(&ct[12..16]) ^ rk[3];

    let mut r = nr >> 1;
    let mut rk_off = 0usize;
    let (mut t0, mut t1, mut t2, mut t3);
    loop {
        t0 = Td0[(s0 >> 24) as usize]
            ^ Td1[((s3 >> 16) & 0xff) as usize]
            ^ Td2[((s2 >> 8) & 0xff) as usize]
            ^ Td3[(s1 & 0xff) as usize]
            ^ rk[rk_off + 4];
        t1 = Td0[(s1 >> 24) as usize]
            ^ Td1[((s0 >> 16) & 0xff) as usize]
            ^ Td2[((s3 >> 8) & 0xff) as usize]
            ^ Td3[(s2 & 0xff) as usize]
            ^ rk[rk_off + 5];
        t2 = Td0[(s2 >> 24) as usize]
            ^ Td1[((s1 >> 16) & 0xff) as usize]
            ^ Td2[((s0 >> 8) & 0xff) as usize]
            ^ Td3[(s3 & 0xff) as usize]
            ^ rk[rk_off + 6];
        t3 = Td0[(s3 >> 24) as usize]
            ^ Td1[((s2 >> 16) & 0xff) as usize]
            ^ Td2[((s1 >> 8) & 0xff) as usize]
            ^ Td3[(s0 & 0xff) as usize]
            ^ rk[rk_off + 7];

        rk_off += 8;
        r -= 1;
        if r == 0 {
            break;
        }

        s0 = Td0[(t0 >> 24) as usize]
            ^ Td1[((t3 >> 16) & 0xff) as usize]
            ^ Td2[((t2 >> 8) & 0xff) as usize]
            ^ Td3[(t1 & 0xff) as usize]
            ^ rk[rk_off];
        s1 = Td0[(t1 >> 24) as usize]
            ^ Td1[((t0 >> 16) & 0xff) as usize]
            ^ Td2[((t3 >> 8) & 0xff) as usize]
            ^ Td3[(t2 & 0xff) as usize]
            ^ rk[rk_off + 1];
        s2 = Td0[(t2 >> 24) as usize]
            ^ Td1[((t1 >> 16) & 0xff) as usize]
            ^ Td2[((t0 >> 8) & 0xff) as usize]
            ^ Td3[(t3 & 0xff) as usize]
            ^ rk[rk_off + 2];
        s3 = Td0[(t3 >> 24) as usize]
            ^ Td1[((t2 >> 16) & 0xff) as usize]
            ^ Td2[((t1 >> 8) & 0xff) as usize]
            ^ Td3[(t0 & 0xff) as usize]
            ^ rk[rk_off + 3];
    }

    s0 = (Td4[(t0 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((t3 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((t2 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(t1 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off];
    put_u32(&mut pt[0..4], s0);
    s1 = (Td4[(t1 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((t0 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((t3 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(t2 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 1];
    put_u32(&mut pt[4..8], s1);
    s2 = (Td4[(t2 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((t1 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((t0 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(t3 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 2];
    put_u32(&mut pt[8..12], s2);
    s3 = (Td4[(t3 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((t2 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((t1 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(t0 & 0xff) as usize] & 0x0000_00ff)
        ^ rk[rk_off + 3];
    put_u32(&mut pt[12..16], s3);
}

/// Partial encrypt for Intermediate Value KAT (`rijndaelEncryptRound`).
///
/// Runs `rounds` full rounds (or `Nr - 1` if `rounds >= Nr`), then applies the
/// final round only when `rounds == Nr`. Requires
/// [`crate::config::INTERMEDIATE_VALUE_KAT`].
pub fn rijndael_encrypt_round(rk: &[u32], nr: i32, block: &mut [u8; 16], rounds: i32) {
    const {
        assert!(crate::config::INTERMEDIATE_VALUE_KAT);
    }
    let mut s0 = get_u32(&block[0..4]) ^ rk[0];
    let mut s1 = get_u32(&block[4..8]) ^ rk[1];
    let mut s2 = get_u32(&block[8..12]) ^ rk[2];
    let mut s3 = get_u32(&block[12..16]) ^ rk[3];
    let mut rk_off = 4usize;

    let mut r = if rounds < nr { rounds } else { nr - 1 };
    while r > 0 {
        let t0 = Te0[(s0 >> 24) as usize]
            ^ Te1[((s1 >> 16) & 0xff) as usize]
            ^ Te2[((s2 >> 8) & 0xff) as usize]
            ^ Te3[(s3 & 0xff) as usize]
            ^ rk[rk_off];
        let t1 = Te0[(s1 >> 24) as usize]
            ^ Te1[((s2 >> 16) & 0xff) as usize]
            ^ Te2[((s3 >> 8) & 0xff) as usize]
            ^ Te3[(s0 & 0xff) as usize]
            ^ rk[rk_off + 1];
        let t2 = Te0[(s2 >> 24) as usize]
            ^ Te1[((s3 >> 16) & 0xff) as usize]
            ^ Te2[((s0 >> 8) & 0xff) as usize]
            ^ Te3[(s1 & 0xff) as usize]
            ^ rk[rk_off + 2];
        let t3 = Te0[(s3 >> 24) as usize]
            ^ Te1[((s0 >> 16) & 0xff) as usize]
            ^ Te2[((s1 >> 8) & 0xff) as usize]
            ^ Te3[(s2 & 0xff) as usize]
            ^ rk[rk_off + 3];
        s0 = t0;
        s1 = t1;
        s2 = t2;
        s3 = t3;
        rk_off += 4;
        r -= 1;
    }

    if rounds == nr {
        let t0 = (Te4[(s0 >> 24) as usize] & 0xff00_0000)
            ^ (Te4[((s1 >> 16) & 0xff) as usize] & 0x00ff_0000)
            ^ (Te4[((s2 >> 8) & 0xff) as usize] & 0x0000_ff00)
            ^ (Te4[(s3 & 0xff) as usize] & 0x0000_00ff)
            ^ rk[rk_off];
        let t1 = (Te4[(s1 >> 24) as usize] & 0xff00_0000)
            ^ (Te4[((s2 >> 16) & 0xff) as usize] & 0x00ff_0000)
            ^ (Te4[((s3 >> 8) & 0xff) as usize] & 0x0000_ff00)
            ^ (Te4[(s0 & 0xff) as usize] & 0x0000_00ff)
            ^ rk[rk_off + 1];
        let t2 = (Te4[(s2 >> 24) as usize] & 0xff00_0000)
            ^ (Te4[((s3 >> 16) & 0xff) as usize] & 0x00ff_0000)
            ^ (Te4[((s0 >> 8) & 0xff) as usize] & 0x0000_ff00)
            ^ (Te4[(s1 & 0xff) as usize] & 0x0000_00ff)
            ^ rk[rk_off + 2];
        let t3 = (Te4[(s3 >> 24) as usize] & 0xff00_0000)
            ^ (Te4[((s0 >> 16) & 0xff) as usize] & 0x00ff_0000)
            ^ (Te4[((s1 >> 8) & 0xff) as usize] & 0x0000_ff00)
            ^ (Te4[(s2 & 0xff) as usize] & 0x0000_00ff)
            ^ rk[rk_off + 3];
        s0 = t0;
        s1 = t1;
        s2 = t2;
        s3 = t3;
    }

    put_u32(&mut block[0..4], s0);
    put_u32(&mut block[4..8], s1);
    put_u32(&mut block[8..12], s2);
    put_u32(&mut block[12..16], s3);
}

/// Partial decrypt for Intermediate Value KAT (`rijndaelDecryptRound`).
pub fn rijndael_decrypt_round(rk: &[u32], nr: i32, block: &mut [u8; 16], rounds: i32) {
    const {
        assert!(crate::config::INTERMEDIATE_VALUE_KAT);
    }
    let mut s0 = get_u32(&block[0..4]) ^ rk[0];
    let mut s1 = get_u32(&block[4..8]) ^ rk[1];
    let mut s2 = get_u32(&block[8..12]) ^ rk[2];
    let mut s3 = get_u32(&block[12..16]) ^ rk[3];
    let mut rk_off = 4usize;

    let mut r = (if rounds < nr { rounds } else { nr }) - 1;
    while r > 0 {
        let t0 = Td0[(s0 >> 24) as usize]
            ^ Td1[((s3 >> 16) & 0xff) as usize]
            ^ Td2[((s2 >> 8) & 0xff) as usize]
            ^ Td3[(s1 & 0xff) as usize]
            ^ rk[rk_off];
        let t1 = Td0[(s1 >> 24) as usize]
            ^ Td1[((s0 >> 16) & 0xff) as usize]
            ^ Td2[((s3 >> 8) & 0xff) as usize]
            ^ Td3[(s2 & 0xff) as usize]
            ^ rk[rk_off + 1];
        let t2 = Td0[(s2 >> 24) as usize]
            ^ Td1[((s1 >> 16) & 0xff) as usize]
            ^ Td2[((s0 >> 8) & 0xff) as usize]
            ^ Td3[(s3 & 0xff) as usize]
            ^ rk[rk_off + 2];
        let t3 = Td0[(s3 >> 24) as usize]
            ^ Td1[((s2 >> 16) & 0xff) as usize]
            ^ Td2[((s1 >> 8) & 0xff) as usize]
            ^ Td3[(s0 & 0xff) as usize]
            ^ rk[rk_off + 3];
        s0 = t0;
        s1 = t1;
        s2 = t2;
        s3 = t3;
        rk_off += 4;
        r -= 1;
    }

    let mut t0 = (Td4[(s0 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((s3 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((s2 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(s1 & 0xff) as usize] & 0x0000_00ff);
    let mut t1 = (Td4[(s1 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((s0 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((s3 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(s2 & 0xff) as usize] & 0x0000_00ff);
    let mut t2 = (Td4[(s2 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((s1 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((s0 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(s3 & 0xff) as usize] & 0x0000_00ff);
    let mut t3 = (Td4[(s3 >> 24) as usize] & 0xff00_0000)
        ^ (Td4[((s2 >> 16) & 0xff) as usize] & 0x00ff_0000)
        ^ (Td4[((s1 >> 8) & 0xff) as usize] & 0x0000_ff00)
        ^ (Td4[(s0 & 0xff) as usize] & 0x0000_00ff);

    if rounds == nr {
        t0 ^= rk[rk_off];
        t1 ^= rk[rk_off + 1];
        t2 ^= rk[rk_off + 2];
        t3 ^= rk[rk_off + 3];
    }

    put_u32(&mut block[0..4], t0);
    put_u32(&mut block[4..8], t1);
    put_u32(&mut block[8..12], t2);
    put_u32(&mut block[12..16], t3);
}

