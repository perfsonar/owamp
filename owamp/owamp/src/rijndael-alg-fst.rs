#[inline]
fn get_u32(pt: &[u8]) -> u32 {
    (u32::from(pt[0]) << 24) ^ (u32::from(pt[1]) << 16) ^ (u32::from(pt[2]) << 8) ^ u32::from(pt[3])
}

#[inline]
const fn put_u32(ct: &mut [u8], st: u32) {
    ct[0] = (st >> 24) as u8;
    ct[1] = (st >> 16) as u8;
    ct[2] = (st >> 8) as u8;
    ct[3] = st as u8;
}

